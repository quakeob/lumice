function setLang(lang) {
  const selected = translations[lang] || translations.en;
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (selected[key]) element.textContent = selected[key];
  });

  document.querySelectorAll('[data-lang]').forEach((button) => {
    button.classList.toggle('active', button.dataset.lang === lang);
  });

  const current = document.getElementById('langCurrent');
  if (current) current.textContent = lang.toUpperCase();
  try { localStorage.setItem('lumice-lang', lang); } catch (_) {}
}

window.setLang = setLang;

const langDropdown = document.getElementById('langDropdown');
const langToggle = document.getElementById('langToggle');

if (langDropdown && langToggle) {
  langToggle.addEventListener('click', (event) => {
    event.stopPropagation();
    const isOpen = langDropdown.classList.toggle('open');
    langToggle.setAttribute('aria-expanded', String(isOpen));
  });

  document.querySelectorAll('[data-lang]').forEach((button) => {
    button.addEventListener('click', () => {
      setLang(button.dataset.lang);
      langDropdown.classList.remove('open');
      langToggle.setAttribute('aria-expanded', 'false');
    });
  });

  document.addEventListener('click', () => {
    langDropdown.classList.remove('open');
    langToggle.setAttribute('aria-expanded', 'false');
  });
}

document.querySelectorAll('[data-scroll-target]').forEach((button) => {
  button.addEventListener('click', () => {
    document.getElementById(button.dataset.scrollTarget)?.scrollIntoView({ behavior: 'smooth' });
  });
});

let initialLanguage = 'en';
try {
  initialLanguage = localStorage.getItem('lumice-lang') || 'en';
} catch (_) {}
setLang(translations[initialLanguage] ? initialLanguage : 'en');
